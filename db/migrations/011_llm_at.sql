-- 011 — отметка «модель это объявление уже видела».
--
-- Слой фактов помечался как `mixed` только если модель что-то дописала. Но
-- «ничего не дописала» — тоже ответ: в тексте этих полей просто нет. Такое
-- объявление оставалось в слое `rules`, то есть в очереди на дозаполнение, и
-- уезжало к модели снова каждые десять минут. На живой базе два объявления
-- набрали 293 и 288 вызовов — сорок процентов всех расходов ушло на то, чтобы
-- триста раз получить один и тот же ответ «не знаю».
--
-- Отметка времени вместо слоя: слой отвечает на вопрос «откуда факты», а
-- llm_at — на вопрос «спрашивали ли». Это разные вопросы, и путать их дорого.

ALTER TABLE listing_facts ADD COLUMN llm_at TEXT;

UPDATE listing_facts SET llm_at = (
    SELECT MAX(u.created_at) FROM llm_usage u WHERE u.listing_id = listing_facts.listing_id
) WHERE llm_at IS NULL;
