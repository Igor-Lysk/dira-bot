-- 017 — отметка «объявление снято с доски».
--
-- Komo мы читаем только с первой страницы, поэтому пропажа из выдачи ничего не
-- доказывает: объявление могли снять, а могли вытеснить новые (решение 0005).
-- Выдача держала такие объявления по дате, 24 дня — и показывала снятые.
-- Первая жалоба пользователя пришла именно на такое: ссылка ведёт на
-- «עמוד לא נמצא».
--
-- В отличие от Homeless, у Komo признак снятия есть: страница снятого
-- объявления отдаёт заголовок «עמוד לא נמצא». Проверяем её и запоминаем.
--
--   removed_at        — когда страница впервые ответила «не найдено»;
--                       такие не идут ни в ленту, ни в очередь отправки
--   alive_checked_at  — когда последний раз проверяли и страница была живой

ALTER TABLE listings ADD COLUMN removed_at TEXT;
ALTER TABLE listings ADD COLUMN alive_checked_at TEXT;

CREATE INDEX IF NOT EXISTS idx_listings_alive ON listings(source, removed_at, missed_scans);
