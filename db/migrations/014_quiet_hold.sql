-- 014 — отметка «доставку придержали тихие часы».
--
-- Мгновенная доставка должна оставаться мгновенной: карточка на объявление,
-- как оно появилось. Списком уходит ровно один случай — то, что накопилось за
-- ночь, пока действовали тихие часы.
--
-- Отличить этот случай по часам было бы приблизительно: доставка просыпается
-- каждые пять минут, «первый час после тихих» — не то же самое, что «первая
-- доставка после тихих». Поэтому отметка ставится в момент, когда доставку
-- действительно придержали, и снимается первой отправкой после.

