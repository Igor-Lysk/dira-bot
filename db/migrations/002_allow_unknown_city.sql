--
-- Первый живой прогон: объявления из хайфского канала не называют город в
-- тексте и проходили тель-авивский фильтр как «город неизвестен». Для признаков
-- квартиры «нет данных — не нарушение» верно, для города — нет: это самый
-- весомый фильтр, половина отказов в v1 была именно по нему.
--
-- По умолчанию 0: объявления без опознанного города не показываем. Пользователь
-- может включить, если готов разбирать такие сам.

ALTER TABLE search_profiles
    ADD COLUMN allow_unknown_city INTEGER NOT NULL DEFAULT 0;
