-- 013 — память о прочитанных сообщениях источника.
--
-- При каждом запуске телеграм-монитор перечитывает трое суток сообщений. Само
-- по себе это дёшево: объявление, которое уже лежит в базе под тем же
-- идентификатором, отсеивается сразу. Но сообщение, признанное повтором другого
-- объявления, следа не оставляло: прежняя запись обновлялась, а идентичность
-- самого сообщения нигде не сохранялась. На следующем запуске оно снова
-- выглядело незнакомым, снова признавалось повтором — и снова возвращало
-- отправленные объявления в очередь.
--
-- За один день так набралось 96 объявлений, отправленных человеку повторно, и
-- 62 записи с переписанной датой сбора. Со стороны это выглядело как «одни и те
-- же квартиры приходят из раза в раз», и правильно выглядело.
--
-- Теперь у каждого прочитанного сообщения есть отметка, независимо от того, чем
-- оно кончилось: новым объявлением, повтором или отказом.

CREATE TABLE IF NOT EXISTS seen_messages (
    source      TEXT NOT NULL,
    key         TEXT NOT NULL,
    listing_id  TEXT,
    outcome     TEXT,
    first_seen  TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY (source, key)
);

-- Всё, что уже в базе, считаем прочитанным: иначе первый же запуск после
-- обновления повторит ровно то, от чего мы уходим.
INSERT OR IGNORE INTO seen_messages (source, key, listing_id, outcome)
SELECT source, COALESCE(source_id, url, id), id, 'new' FROM listings;
