-- 015 — отметка «подобрано под прежние критерии».
--
-- Сужение критериев убирает из очереди неотправленное, но уже показанные
-- карточки остаются: они принадлежат истории человека, а не текущим настройкам.
-- Беда в том, что лента показывает и их. Профиль «Тель-Авив до 5000», а в
-- ленте квартира в Рамат-Гане за 7500, подобранная час назад под прежние
-- настройки. Со стороны это ровно «фильтр не работает».
--
-- Отдельная отметка вместо удаления: запись о том, что человеку это уже
-- отправляли, нужна и для повторных отправок, и для статистики. В ленту такие
-- не идут, пока не подойдут снова — тогда отметка снимается.

ALTER TABLE matches ADD COLUMN stale_at TEXT;

CREATE INDEX IF NOT EXISTS idx_matches_stale ON matches(profile_id, stale_at);
