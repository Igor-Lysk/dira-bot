-- накопления пришло 84 объявления и 18 подходящих. Предел, стоящий на уровне
-- потока, срабатывает через день и молча прячет квартиры — для поиска жилья
-- это худший отказ, хороший вариант уходит за час.
--
-- Смысл ограничения остаётся ровно один: не дать боту вывалить всю базу при
-- ошибке в критериях или догоняющем сборе после простоя.

