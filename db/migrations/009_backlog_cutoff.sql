-- 009 — граница накопленного и уведомление об исчерпанном лимите.
--
-- Мгновенная доставка захлебнулась на первом же дне: в очереди лежало двести
-- совпадений, накопленных до того, как профиль был настроен, и весь дневной
-- лимит ушёл на них за одну минуту. Дальше одиннадцать часов тишины при живом
-- потоке — новые объявления приходили, но места в лимите уже не было.
--
-- Накопленное до настройки профиля — это материал для /feed, а не повод будить
-- человека: он и так видит «уже нашлось: N» в конце визарда. Мгновенно шлём
-- только то, что появилось после. Граница ставится один раз, при создании
-- профиля; смена критериев её не двигает — иначе каждая правка потолка цены
-- превращалась бы в рассылку по всей базе.
--
-- Существующим профилям граница ставится по текущему моменту: всё, что лежит
-- в очереди сейчас, объявляется накопленным.

ALTER TABLE search_profiles ADD COLUMN backlog_before TEXT;
ALTER TABLE search_profiles ADD COLUMN cap_notice_on  TEXT;

UPDATE search_profiles SET backlog_before = datetime('now') WHERE backlog_before IS NULL;
